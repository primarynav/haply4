// Community starter content. Emits two artifacts from one source so they can't drift:
//   src/haply/communityPosts.ts  — the client-side fallback / pre-fetch state
//   supabase/seed/posts.sql      — rows for the live posts table
// Run: node scripts/seed-posts.mjs
//
// WHAT THIS DELIBERATELY NO LONGER CONTAINS
//
// This file used to seed 27 posts under invented member names — "Marcus T.",
// "Dana R." — each carrying invented personal testimony about signing divorce
// papers, crying children at custody handoffs, and therapy. They also carried
// invented like and comment counts in the hundreds.
//
// It is the same mistake data.ts already rejects for profiles, and it is worse
// here. A fake profile is a padded number; a fake confession about someone's
// 6-year-old is fabricated intimate testimony, published under a name, on a
// product whose entire premise is that it verifies members are who they claim.
// The first journalist or member who diffs the seed file against the member
// count has the story, and in this category trust is the product — it is the
// only thing Haply sells that SilverSingles cannot buy.
//
// So: operator content only. Every post below is genuinely written by the Haply
// team, posts under the team's own name, and claims nothing about a member who
// does not exist. Empty categories stay empty until real people fill them. If
// you are tempted to add "just a few" member posts to make the feed look alive,
// read the note in src/haply/data.ts first — an empty room is recoverable, a
// room full of invented grief is not.
//
// Engagement counts are hardcoded 0. They are not columns on posts; fetchPosts()
// derives them from post_likes and comments. Any nonzero number written here is
// a fabrication that the live feed will contradict anyway.
import { writeFileSync, mkdirSync } from 'node:fs';

