const label = (h) => {
  if (h === 0) return 'Pinned';
  if (h < 1) return 'Just now';
  if (h < 24) return `${h} hours ago`;
  const d = Math.round(h / 24);
  return d === 1 ? '1 day ago' : `${d} days ago`;
};

// --- TypeScript fallback ---
const ts = `// AUTO-GENERATED by scripts/seed-posts.mjs — do not edit by hand.
// Client-side fallback and pre-fetch state, shown only if the live fetch fails.
// The live feed is served from the Supabase \`posts\` table; seed it with
// supabase/seed/posts.sql.
//
// Operator content only — these are conversation prompts written by the Haply
// team under the team's own name. No invented members, no invented engagement
// counts. See the header of scripts/seed-posts.mjs for why.
import type { Post } from './data';

export const COMMUNITY_POSTS: Post[] = [
${POSTS.map((p, i) => `  ${JSON.stringify({ id: i + 1, name: p.name, cat: p.cat, time: label(p.hoursAgo), title: p.title, body: p.body, likes: 0, comments: 0 })},`).join('\n')}
];
`;
writeFileSync('src/haply/communityPosts.ts', ts);

// --- SQL seed ---
const esc = (s) => s.replace(/'/g, "''");
const rows = POSTS.map(
  (p) =>
    `  (${p.pinned ? 'true' : 'false'}, '${esc(p.name)}', '${esc(p.cat)}', '${esc(p.title)}', '${esc(p.body)}', now() - interval '${p.hoursAgo} hours')`
).join(',\n');

const sql = `-- AUTO-GENERATED by scripts/seed-posts.mjs — do not edit by hand.
-- Seeds the community feed with the team's opening conversation prompts.
--
-- Run in the Supabase SQL editor.
--
-- Safe to re-run: each row is skipped when a post with the same title already
-- exists, so this does not depend on a unique constraint and will not duplicate.
--
-- OPERATOR CONTENT ONLY. Every row is written by the Haply team and posts under
-- the team's name. This file previously seeded 27 posts under invented member
-- names carrying invented personal testimony; they were deleted from the live
-- table and must not come back. See scripts/seed-posts.mjs for the reasoning.
--
-- Engagement counts are not seeded and not seedable: likes and comments are not
-- columns on posts, fetchPosts() derives them from the post_likes and comments
-- relations, and post_likes is keyed by (post_id, user_id) — so a realistic
-- count would require inventing one user row per like.
--
-- user_id is left NULL: the column is nullable, and these posts are not authored
-- by any real member account. Attributing them to a member's uuid would make them
-- look like that person's posts to anything that reads user_id.

with seed(pinned, author_name, cat, title, body, created_at) as (
  values
${rows}
)
insert into public.posts (user_id, author_name, cat, title, body, pinned, created_at)
select
  null,
  s.author_name, s.cat, s.title, s.body, s.pinned, s.created_at
from seed s
where not exists (select 1 from public.posts p where p.title = s.title);

-- Verify — every seeded row should read 'Haply Team':
--   select author_name, count(*) from public.posts where user_id is null group by 1;
--   select author_name, title, created_at from public.posts order by created_at desc limit 10;
`;
mkdirSync('supabase/seed', { recursive: true });
writeFileSync('supabase/seed/posts.sql', sql);

const byCat = {};
for (const p of POSTS) byCat[p.cat] = (byCat[p.cat] || 0) + 1;
